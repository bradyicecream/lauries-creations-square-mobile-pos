const assert=require('node:assert/strict');
const fs=require('node:fs');
const settings=require('../app/src/main/assets/settings-addons.js');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const app=fs.readFileSync('app/src/main/assets/app.js','utf8');
const ui=fs.readFileSync('app/src/main/assets/settings-addons-ui.js','utf8');
const css=fs.readFileSync('app/src/main/assets/settings-addons.css','utf8');
const v19={products:[],cart:[],favoriteGroups:[],taxPercent:0,chargeSettings:{}};
const pref=settings.normalize(v19);
assert.equal(pref.quickAddSimpleItems,true);
assert.equal(pref.showStockOnTiles,true);
assert.equal(pref.compactFavoritesGrid,true);
assert.equal(pref.confirmClearSale,true);
assert.equal(pref.showEmptyGridSlots,true);
assert.equal(settings.counts().total>=50,true,'Includes comprehensive settings catalog');
assert.equal(settings.categories.length>=7,true,'Organized across many business areas');
for(const group of settings.categories){
 assert.ok(group.name&&group.icon);
 for(const row of group.entries){
   const target=settings.lookup(row[0]);
   assert.ok(target&&target.name===row[1],'Every setting resolves via directory');
   assert.ok(['local','preview','square','hardware','subscription'].includes(target.status),'Honest status required');
 }
}
const ids=settings.categories.flatMap(g=>g.entries.map(e=>e[0]));
assert.equal(ids.length,new Set(ids).size,'Every add-on has a distinct key');
assert.equal(settings.lookup('squareCatalog').status,'square','Live Catalog not falsely connected');
assert.equal(settings.lookup('banking').status,'square','Banking not falsely connected');
assert.equal(settings.lookup('loyalty').status,'subscription','Square Loyalty subscription not mocked');
assert.equal(settings.lookup('customerPreview').status,'preview','Customer display still local preview');
assert.equal(settings.lookup('cash').status,'local','Local cash management available');
assert.equal(settings.lookup('tax').status,'local','No-tax register setting documented');
assert.equal(settings.update(v19,'quickAddSimpleItems',false),true);
assert.equal(settings.update(v19,'compactFavoritesGrid',false),true);
assert.equal(settings.update(v19,'showEmptyGridSlots',false),true);
assert.equal(settings.update(v19,'confirmClearSale',false),true);
assert.equal(settings.update(v19,'showStockOnTiles',false),true);
assert.equal(settings.update(v19,'connectedSquare',true),false,'Cannot invent connection by setting a switch');
assert.equal(settings.update(v19,'quickAddSimpleItems','off'),false,'Reject nonboolean input');
const backup=JSON.parse(JSON.stringify(v19));settings.normalize(backup);
assert.deepEqual(backup.registerPreferences,v19.registerPreferences,'Preferences survive JSON backups');
assert.equal(backup.registerPreferences.quickAddSimpleItems,false);
backup.registerPreferences={quickAddSimpleItems:'bad',showStockOnTiles:false};
assert.equal(settings.normalize(backup).quickAddSimpleItems,true,'Malformed settings revert to safe default');
assert.equal(settings.normalize(backup).showStockOnTiles,false,'Valid existing preference preserved');
for(const id of ['settingsAndAddons','registerPrefsFromMore'])assert.ok(html.includes('id="'+id+'"'),'More menu button '+id);
for(const src of ['settings-addons.js','settings-addons-ui.js'])assert.ok(html.includes('src="'+src+'"'),'Script included '+src);
assert.ok(html.indexOf('settings-addons.js')<html.indexOf('settings-addons-ui.js'));
assert.ok(html.indexOf('settings-addons-ui.js')<html.indexOf('app.js'));
assert.ok(html.includes('href="settings-addons.css"'));
assert.ok(app.includes('preferencesApi.normalize(state).quickAddSimpleItems'),'Quick add setting actually changes checkout');
assert.ok(app.includes('preferencesApi.normalize(state).showStockOnTiles'),'Stock label setting works');
assert.ok(app.includes('preferencesApi.normalize(state).showEmptyGridSlots'),'Empty grid slots setting works');
assert.ok(app.includes("document.body.classList.toggle('registerExpandedTiles'"),'Tile density setting applies');
assert.ok(app.includes('preferencesApi.normalize(state).confirmClearSale'),'Clear cart confirmation configurable');
assert.ok(app.includes('settingsUI.hub()'),'Settings hub opens');
assert.ok(app.includes('preferencesApi.normalize(state);state.taxPercent=0;'),'Backup migration preserves no tax');
assert.ok(ui.includes('getState()'),'Settings UI follows imported register state');
assert.ok(ui.includes('root.LaurieSquare?.openSquareDashboard'),'Square services link to official site without capturing tokens');
assert.ok(ui.includes('not activated'),'Unconnected services clearly labeled');
assert.ok(css.includes('.settingsToggle'),'Mobile-friendly toggles styled');
assert.ok(html.includes('Gratuity &amp; service charge'),'Existing card-only Gratuity settings preserved');
console.log('Settings/add-ons directory, local preferences, backup, honest statuses and register integration passed.');
