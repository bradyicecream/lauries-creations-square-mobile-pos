const assert=require('node:assert/strict');
const fs=require('node:fs');
const base='app/src/main/';
const gradle=fs.readFileSync('app/build.gradle','utf8');
const application=fs.readFileSync(base+'java/com/lauriescreations/mobile/LaurieApplication.kt','utf8');
const activity=fs.readFileSync(base+'java/com/lauriescreations/mobile/MainActivity.kt','utf8');
const app=fs.readFileSync(base+'assets/app.js','utf8');
const operations=fs.readFileSync(base+'assets/operations-ui.js','utf8');
const model=fs.readFileSync(base+'assets/operations-model.js','utf8');
const manifest=fs.readFileSync(base+'AndroidManifest.xml','utf8');
assert.ok(gradle.includes("paymentEnvironment")&&gradle.includes("'sandbox'"),'Sandbox remains default');
assert.ok(gradle.includes("versionName isProduction ? '1.0.0-production' : '1.12.0-sandbox'"),'Environment versions separated');
assert.ok(gradle.includes("com.lauriescreations.mobile.production"),'Production application package separated');
assert.ok(gradle.includes("productionKeystorePath"),'Release requires private production signing');
assert.ok(gradle.includes("assembleRelease")||gradle.includes("contains('release')"),'Release-only production gate');
assert.ok(!gradle.includes('accessToken='),'No OAuth access token embedded in Gradle');
assert.ok(application.includes("MobilePaymentsSdk.isSandboxEnvironment() != BuildConfig.IS_PRODUCTION"),'SDK environment matches app mode');
assert.ok(activity.includes('HttpsURLConnection'),'Token obtained only over native HTTPS');
assert.ok(activity.includes('production-redeem'),'Explicit pairing endpoint');
assert.ok(activity.includes('locationId != "LHV4RK9G8JN4T"'),'Pin expected Square location');
assert.ok(!activity.includes('addJavascriptInterface(RegisterBridge(), "ProductionToken")'),'No production token bridge');
assert.ok(activity.includes('put("sandbox", !BuildConfig.IS_PRODUCTION)'),'Payment event identifies environment');
assert.ok(activity.includes('if (!BuildConfig.IS_PRODUCTION && squareReady'),'Mock reader never launches on production');
assert.ok(activity.includes("MockReaderUI.show()"),'Sandbox mock reader kept');
assert.ok(operations.includes("REAL CARD CHARGE"),'Explicit confirmation on production payments');
assert.ok(operations.includes("authorized-production"),'SDK authorization required for production');
assert.ok(model.includes("production-card"),'Record real card payment distinctly');
assert.ok(app.includes("msg.sandbox===false?'production-card':'sandbox-card'"),'Use distinct records for real vs test');
assert.ok(app.includes("PRODUCTION MODE • REAL PAYMENTS"),'Clear production status');
assert.ok(manifest.includes('android:usesCleartextTraffic="false"'),'No insecure Android HTTP');
console.log('Production signature gating, HTTPS native pairing, real-charge confirmation and Sandbox isolation validated.');
