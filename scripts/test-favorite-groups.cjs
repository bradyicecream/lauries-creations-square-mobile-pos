const assert=require('node:assert/strict');
const groups=require('../app/src/main/assets/favorite-groups.js');
const products=['beads','fidget','tumbler','icecream'].map(id=>({id,name:id}));
const legacy={products,favorites:['fidget','beads','fidget','missing'],cart:[]};
groups.normalize(legacy);
assert.equal(legacy.favoriteGroups.length,1,'Migrates old favorites to a single group');
assert.deepEqual(legacy.favoriteGroups[0].productIds,['fidget','beads','missing'],'Preserves ordering and unknown ids for potential future catalog restores');
assert.equal(legacy.favoriteGroups[0].name,'Favorites');
const first=legacy.favoriteGroups[0].id;
assert.equal(legacy.activeFavoriteGroupId,first);
assert.equal(groups.addGroup(legacy,'  Holiday  Specials  ').ok,true);
const second=legacy.activeFavoriteGroupId;
assert.equal(groups.active(legacy).name,'Holiday Specials');
assert.equal(groups.addGroup(legacy,'holiday specials').ok,false,'Rejects duplicate names case insensitively');
assert.equal(groups.renameGroup(legacy,second,'  Fall Finds  ').ok,true);
assert.equal(groups.renameGroup(legacy,second,'Favorites').ok,false,'Reject duplicate tab rename');
assert.equal(groups.setProducts(legacy,second,['tumbler','fidget']),true);
assert.deepEqual(groups.active(legacy).productIds,['fidget','tumbler'],'New favorites follow product library order');
assert.equal(groups.toggleProduct(legacy,second,'beads'),true,'Adds selected library item');
assert.equal(groups.toggleProduct(legacy,second,'beads'),false,'Unstars item');
assert.deepEqual(groups.active(legacy).productIds,['fidget','tumbler']);
assert.equal(groups.moveProduct(legacy,second,'tumbler',-1),true,'Reorders items');
assert.deepEqual(groups.active(legacy).productIds,['tumbler','fidget']);
assert.equal(groups.moveProduct(legacy,second,'tumbler',-1),false,'Cannot move past edge');
assert.equal(groups.moveGroup(legacy,second,-1),true,'Reorders tabs');
assert.equal(legacy.favoriteGroups[0].id,second);
assert.deepEqual(legacy.favorites,['tumbler','fidget'],'Legacy compatibility follows first group');
assert.equal(groups.removeGroup(legacy,second),true);
assert.equal(legacy.favoriteGroups.length,1);
assert.equal(legacy.activeFavoriteGroupId,first);
assert.deepEqual(legacy.products,products,'Deleting a group does not delete products');
assert.equal(groups.removeGroup(legacy,first),false,'Cannot delete the only tab');
const saved=JSON.parse(JSON.stringify(legacy));
groups.normalize(saved);
assert.equal(saved.favoriteGroups.length,1,'Groups persist through JSON serialization');
assert.equal(saved.activeFavoriteGroupId,first);
assert.deepEqual(saved.favoriteGroups[0].productIds,['fidget','beads','missing']);
const alreadySet={products,favoriteGroups:[{id:'m',name:'Regulars',productIds:['icecream']},{id:'n',name:'Events',productIds:[]}],activeFavoriteGroupId:'n'};
groups.normalize(alreadySet);
assert.equal(alreadySet.activeFavoriteGroupId,'n','Preserves active group on upgrade');
assert.equal(alreadySet.favoriteGroups[0].name,'Regulars','Preserves custom tab names');
assert.equal(groups.toggleProduct(alreadySet,'n','not-in-library'),false,'Cannot add nonexistent products');
console.log('Favorites group migration, add, rename, remove, reorder, save, and membership tests passed.');
