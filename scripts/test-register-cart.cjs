const assert=require('node:assert/strict');
const cart=require('../app/src/main/assets/register-cart.js');
const p={id:'autism',name:'Autism awareness',price:100,variants:[],scoops:0,extras:[],reviewRequired:false};
const product=(changes={})=>({...p,...changes});
assert.equal(cart.canQuickAdd(p,0),true,'Simple product adds without modal');
assert.equal(cart.canQuickAdd(product({variants:['Purple']}),0),false,'Variation needs item editor');
assert.equal(cart.canQuickAdd(product({scoops:2}),0),false,'Ice cream needs flavor editor');
assert.equal(cart.canQuickAdd(product({extras:[{name:'Gift wrap',price:50}]}),0),false,'Local modifier needs editor');
assert.equal(cart.canQuickAdd(p,1),false,'Shared modifiers need editor');
assert.equal(cart.canQuickAdd(product({price:null}),0),false,'Missing price must not quick-add');
assert.equal(cart.canQuickAdd(product({reviewRequired:true}),0),false,'Unverified saved product must not quick-add');
const state={saleId:'sale1',paidSaleId:null,cart:[],saleNote:'Remember purple ribbon'};
let made=0;
let result=cart.addSimple(state,p,()=>String(++made));
assert.equal(result.ok,true);
assert.equal(state.cart[0].qty,1);
result=cart.addSimple(state,p,()=>String(++made));
assert.equal(result.merged,true,'Repeated taps combine into one cart line');
assert.equal(state.cart[0].qty,2);
assert.equal(state.cart[0].price,100);
assert.equal(state.saleNote,'Remember purple ribbon','Quick-add does not modify notes');
result=cart.adjustQuantity(state,0,1);
assert.equal(result.ok,true);
assert.equal(state.cart[0].qty,3);
result=cart.adjustQuantity(state,0,-1);
assert.equal(state.cart[0].qty,2);
cart.adjustQuantity(state,0,-1);
result=cart.adjustQuantity(state,0,-1);
assert.equal(result.removed,true,'Minus on quantity one removes line');
assert.equal(state.cart.length,0);
assert.equal(cart.adjustQuantity(state,0,-1).ok,false,'Missing line ignored');
cart.addSimple(state,p,()=>String(++made));
state.cart[0].qty=99;
assert.equal(cart.adjustQuantity(state,0,1).reason,'maximum','Qty stops at 99');
result=cart.addSimple(state,p,()=>String(++made));
assert.equal(result.merged,false,'Additional tap at max 99 creates another line');
assert.equal(state.cart.length,2);
state.paidSaleId='sale1';
assert.equal(cart.adjustQuantity(state,0,-1).ok,false,'Completed sales cannot change');
assert.equal(cart.addSimple(state,p,()=>String(++made)).ok,false,'Completed sales cannot be added to');
assert.equal(state.cart.length,2,'No mutation after payment');
const copy=JSON.parse(JSON.stringify(state));
assert.equal(copy.cart[0].qty,99,'Cart persists through backup');
console.log('One-tap checkout and quantity edits passed.');
