const assert=require('node:assert/strict');
const ops=require('../app/src/main/assets/operations-model.js');
const makeState=()=>({products:[{id:'a',name:'Bracelet',category:'Beads'},{id:'b',name:'Ice cream',category:'Ice Cream'}],
  cart:[{productId:'a',name:'Bracelet',price:750,qty:2,needsReview:false,extras:[],flavors:[]}],
  taxPercent:10,saleId:'sale-001',paidSaleId:null,operations:null});
const s=makeState();const o=ops.normalize(s);
assert.equal(o.staff.length,0);assert.equal(o.cashSessions.length,0);
const staff=ops.addStaff(s,'  Laurie  ');
assert.equal(staff.ok,true);assert.equal(staff.row.name,'Laurie');
assert.equal(ops.addStaff(s,'laurie').ok,false);
assert.equal(ops.clock(s,staff.row.id,1000).type,'in');
assert.equal(ops.clock(s,staff.row.id,3601000).type,'out');
assert.equal(o.timecards[0].end-o.timecards[0].start,3600000);
assert.equal(o.activeStaffId,null,'Clocking out clears active staff assignment');
assert.equal(ops.clock(s,staff.row.id,3602000).type,'in');
assert.equal(o.activeStaffId,staff.row.id,'Clocked-in staff selected for local sales');
assert.equal(ops.setInventory(s,'a',true,4,2).ok,true);
assert.equal(ops.available(s,'a',4),true);
assert.equal(ops.available(s,'a',5),false);
assert.deepEqual(ops.quickCashAmounts(1299).slice(0,3),[1299,1500,2000]);
assert.deepEqual(ops.quickCashAmounts(0),[]);
assert.equal(ops.tipAmount(1500,'percentage',20),300);
assert.equal(ops.tipAmount(1500,'fixed',175),175);
assert.equal(ops.tipAmount(1500,'percentage',200),null);
assert.equal(ops.tipAmount(1500,'fixed',-1),null);
assert.equal(ops.openCash(s,2000).ok,true);
assert.equal(ops.openCash(s,1000).ok,false,'Only one cash session');
const cust=ops.addCustomer(s,'Customer A');
assert.equal(cust.ok,true);o.selectedCustomerId=cust.row.id;
const card=ops.recordSale(s,'local-cash',300,2000);
assert.equal(card.ok,true);
assert.equal(card.row.subtotalCents,1500);
assert.equal(card.row.taxCents,150);
assert.equal(card.row.tipCents,300);
assert.equal(card.row.totalCents,1950);
assert.equal(card.row.changeCents,50);
assert.equal(ops.inventoryRecord(s,'a').quantity,2,'Stock deducted once');
assert.equal(card.row.staffId,staff.row.id,'Local sale records active staff member');
assert.equal(o.customers[0].points,15,'Points per whole dollar of subtotal');
assert.equal(ops.expectedCash(s,card.row.sessionId),3950,'Expected cash includes opening and full sale');
assert.equal(ops.adjustCash(s,100,'Register float adjustment').ok,true);
assert.equal(ops.adjustCash(s,-100,'Supply purchase').ok,true);
assert.equal(ops.expectedCash(s,card.row.sessionId),3950,'Paid-in and paid-out movements reconcile');
assert.equal(ops.adjustCash(s,0,'No value').ok,false,'Zero adjustment disallowed');
assert.equal(o.cashMovements.length,2);
assert.equal(ops.recordSale(s,'local-cash',300,2000).ok,false,'Idempotent sale record');
assert.equal(ops.inventoryRecord(s,'a').quantity,2,'Duplicate cannot subtract twice');
assert.equal(ops.closeCash(s,3900).variance,-50,'Cash short variance');
assert.equal(ops.currentCash(s),null);
s.saleId='sale-002';s.paidSaleId=null;
const sandbox=ops.recordSale(s,'sandbox-card',0,null,'sq-test-payid');
assert.equal(sandbox.ok,true,'Sandbox payment is recorded locally after confirmed callback');
assert.equal(ops.inventoryRecord(s,'a').quantity,0,'New sale subtracts remaining stock');
assert.equal(ops.expectedCash(s,card.row.sessionId),3950,'Sandbox does not change cash balance');
s.saleId='sale-003';s.paidSaleId=null;
assert.equal(ops.recordSale(s,'local-cash',0,2000).ok,false,'Cash requires open session');
assert.equal(ops.recordSale(s,'sandbox-card',0,null,'sq-2').ok,false,'Out of stock blocks sale');
const snapshot=JSON.parse(JSON.stringify(s));ops.normalize(snapshot);
assert.equal(snapshot.operations.salesRecords.length,2);
assert.equal(snapshot.operations.staff.length,1);
assert.equal(snapshot.operations.timecards.length,2,'Completed and active timecards persist');
assert.equal(snapshot.operations.customers[0].points,30,'Loyalty points persisted in JSON backup');
assert.equal(ops.adjustLoyalty(snapshot,cust.row.id,-31).ok,false,'Cannot redeem more points than available');
assert.equal(ops.adjustLoyalty(snapshot,cust.row.id,-20).ok,true);
assert.equal(snapshot.operations.customers[0].points,10);
const empty=makeState();ops.normalize(empty);
assert.equal(ops.recordSale(empty,'sandbox-card',0,null,'').ok,true);
assert.equal(ops.available(empty,'a',1000),true,'Untracked stock is not limited');
console.log('Local operations: staff/timecards, cash drawer, inventory, quick tender amounts, tips, loyalty, idempotent sales passed.');
