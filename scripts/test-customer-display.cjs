const assert=require('node:assert/strict');
const fs=require('node:fs');
const root='app/src/main/';
const app=fs.readFileSync(root+'assets/app.js','utf8');
const ops=fs.readFileSync(root+'assets/operations-ui.js','utf8');
const customer=fs.readFileSync(root+'assets/customer-display.html','utf8');
const native=fs.readFileSync(root+'java/com/lauriescreations/mobile/CustomerDisplayServer.kt','utf8');
const activity=fs.readFileSync(root+'java/com/lauriescreations/mobile/MainActivity.kt','utf8');
const gradle=fs.readFileSync('app/build.gradle','utf8');
assert.ok(app.includes('publishCustomerDisplay();'),'Every cart render must publish customer snapshot');
for(const value of ['items,','cashTotalCents','cardTotalCents','cardGratuityCents','incomplete','paid'])
  assert.ok(app.includes(value),'Snapshot includes '+value);
assert.ok(app.includes('state.flavors.find'),'Flavor names included');
assert.ok(ops.includes('Live customer-facing display'),'Live pairing in More menu');
assert.ok(ops.includes('details.pairingCode'),'Customer code shown on cashier');
assert.ok(customer.includes("fetch('/state'"),'Customer must poll actual server');
assert.ok(customer.includes('X-Display-Code'),'Read endpoint must use pairing code');
assert.ok(customer.includes('textContent'),'Dynamic cart details must be rendered as text');
assert.ok(!customer.includes('innerHTML'),'Untrusted item names may not become HTML');
assert.ok(!customer.includes('squareup.com'),'No Square secrets or Square checkout on public screen');
assert.ok(native.includes('SecureRandom()'),'Unpredictable pairing code');
assert.ok(native.includes('if (pin == code)'),'Live state gated by pairing code');
assert.ok(native.includes('Cache-Control: no-store'),'No cached order details');
assert.ok(native.includes('latest.set('),'Native server stores updated public snapshot');
assert.ok(activity.includes('customerDisplay = CustomerDisplayServer(assets).also { it.start() }'),'Server starts with register');
assert.ok(activity.includes('customerDisplay.stop()'),'Server stops on shutdown');
assert.ok(activity.includes('@JavascriptInterface fun displayPublish('),'Native bridge receives cart');
assert.ok(gradle.includes("'1.12.0-sandbox'"),'Sandbox version preserved');
console.log('Live customer display pairing, safe public payload, and refresh wiring validated.');
